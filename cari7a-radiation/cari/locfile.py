"""Build CARI-7A location (.LOC) files.

Data line format (comma separated, <= 66 characters or CARI emits junk lines):
    N/S, LAT, E/W, LON, G/F/K, ALT, YYYY/MM/DD, H#, D#, P#, C#, S#
"""
from __future__ import annotations

from dataclasses import dataclass

MAX_LINE = 66

# Particle codes as listed in the CARI-7A LOC file help block.
PARTICLES = {
    0: "Total ions", 1: "Neutrons", 2: "Photons", 3: "Electrons", 4: "Positrons",
    5: "Neg. muons", 6: "Pos. muons", 7: "Protons", 8: "Pos. pions", 9: "Neg. pions",
    10: "Deuterons", 11: "Tritons", 12: "Helions", 13: "Alphas",
}
_ELEMENTS = ["Li", "Be", "B", "C", "N", "O", "F", "Ne", "Na", "Mg", "Al", "Si", "P", "S",
             "Cl", "Ar", "K", "Ca", "Sc", "Ti", "V", "Cr", "Mn", "Fe"]
for _i, _el in enumerate(_ELEMENTS):
    PARTICLES[14 + _i] = _el


def particle_z(code: int) -> int | None:
    """Atomic number for nuclear species codes (protons=1 ... Fe=26); None otherwise."""
    if code == 7:
        return 1
    if code in (10, 11):
        return 1
    if code in (12, 13):
        return 2
    if 14 <= code <= 37:
        return code - 11
    return None


# Dose codes used by this tool (D#). Units are as CARI reports them.
DOSES = {
    5: ("absorbed_wb", "Whole-body avg absorbed dose", "µGy/h"),
    6: ("si_0p5mm", "Absorbed dose in 0.5 mm Si", "µGy/h"),
    7: ("si_0p3mm", "Absorbed dose in 0.3 mm Si", "µGy/h"),
}


@dataclass(frozen=True)
class Query:
    alt_ft: float
    dose_code: int  # D#
    particle: int  # P#

    @property
    def key(self) -> str:
        if self.dose_code == 1:
            return f"flux_P{self.particle}"
        return DOSES[self.dose_code][0]


def format_line(lat: float, lon: float, q: Query, year: int, month: int, day: int = 0,
                gcr_model: int = 4, superpos: int = 0) -> str:
    ns = "N" if lat >= 0 else "S"
    ew = "E" if lon >= 0 else "W"
    line = (f"{ns},{abs(lat):.4f},{ew},{abs(lon):.4f},F,{q.alt_ft:.0f},"
            f"{year:04d}/{month:02d}/{day:02d},H0,D{q.dose_code},P{q.particle},"
            f"C{gcr_model},S{superpos}")
    if len(line) > MAX_LINE:
        raise ValueError(f"LOC line exceeds {MAX_LINE} chars: {line!r}")
    return line


def build_loc(lat: float, lon: float, queries: list[Query], year: int, month: int,
              day: int = 0, title: str = "generated by cari7a-radiation") -> str:
    lines = [title[:60], "START-------------------------------"]
    lines += [format_line(lat, lon, q, year, month, day) for q in queries]
    lines.append("STOP--------------------------------")
    return "\r\n".join(lines) + "\r\n"
